#!/usr/bin/env python3
"""the long tail, borrowed from sherlock (github.com/sherlock-project/sherlock, MIT) -> sites/80-more.yaml
a site only gets in if its canary passes three times from here, the most popular ones fill the grid up to 200. refresh with ./sherlock.py"""
import concurrent.futures, io, pathlib, re, urllib.parse, zipfile, requests, yaml, check

DATA = "https://raw.githubusercontent.com/sherlock-project/sherlock/master/sherlock_project/resources/data.json"
RANKS = "https://tranco-list.eu/top-1m.csv.zip"  # popularity: the 200 slots go to the best known sites
SKIP = re.compile("forum|community|discuss|nyaa|pr0gramm|hackerearth|irecommend|figma|weblate|artstation|cashapp|themeforest")  # not what we want, flaky, or closed to servers
OUT = pathlib.Path(__file__).parent / "sites/80-more.yaml"
HEAD = """# generated by ./sherlock.py from sherlock's data.json - edit there or promote a site into a hand-written file.
# Copyright (c) 2019 Sherlock Project, MIT License: https://github.com/sherlock-project/sherlock/blob/master/LICENSE
"""


def domain(url): return ".".join((urllib.parse.urlparse(url).hostname or "").split(".")[-2:])


def convert(s):
    """sherlock entry -> our entry (or None if we cannot check it exactly)"""
    url = s.get("urlProbe", s["url"])
    if s.get("isNSFW") or "{}" not in url or domain(url) != domain(s["url"]) or s["errorType"] == "response_url": return
    site = {"url": url, "link": s["url"], "signup": s["urlMain"], "known": s["username_claimed"].lower()}
    site |= {ours: s[theirs] for theirs, ours in (("request_method", "method"), ("request_payload", "json"), ("headers", "headers")) if s.get(theirs, "GET") != "GET"}
    if simple := re.fullmatch(r"\^?\[([^]]+)]\{(\d+),(\d+)}\$?", s.get("regexCheck", "")): site |= {"chars": simple[1], "length": f"{simple[2]}-{simple[3]}"}
    elif "regexCheck" in s: site["valid"] = s["regexCheck"]
    if s["errorType"] == "status_code": return site | {"taken": {"status": 200}, "free": {"status": s.get("errorCode", 404)}}
    try: found, missing = (check.TRANSPORTS["url"](site | {"free": {"contains": ""}}, n).text.lower() for n in (site["known"], "qzxvkwpjhtmy42"))
    except Exception: return
    said = [m for m in check.many(s["errorMsg"]) if m.lower() in missing and m.lower() not in found]
    echo = site["known"] in found  # a profile that shows the name is real evidence, a page that merely lacks the error is not
    return said and site | {"taken" if echo else "probably_taken": {"status": 200, "lacks": said[0]} | ({"contains": "{}"} if echo else {}), "free": {"contains": said[0]}}


def passes(key):
    try: return all(check.healthy(key) for _ in range(3))
    except Exception: return False


if __name__ == "__main__":
    own = {k: v for k, v in check.SITES.items() if v["group"] != "more"}
    taken = {domain(v[k]) for v in own.values() for k in ("url", "link") if k in v}
    data = {re.sub(r"[^a-z0-9]", "", k.lower()): v | {"name": k} for k, v in requests.get(DATA, timeout=20).json().items() if isinstance(v, dict) and "url" in v}
    data = {k: v for k, v in data.items() if k not in own and domain(v["url"]) not in taken}
    with concurrent.futures.ThreadPoolExecutor(48) as pool:
        sites = {k: {"name": data[k]["name"]} | s for k, s in zip(data, pool.map(convert, data.values())) if s}
        check.SITES.clear(), check.SITES.update(sites)
        good = [k for k, ok in zip(sites, pool.map(passes, sites)) if ok]
    rank = {line.split(",")[1]: i for i, line in enumerate(zipfile.ZipFile(io.BytesIO(requests.get(RANKS, timeout=60).content)).read("top-1m.csv").decode().split())}
    best = sorted((k for k in good if not SKIP.search(k)), key=lambda k: rank.get(domain(sites[k]["url"]), 10**7))[:200 - len(own)]
    OUT.write_text(HEAD + "".join(f"{k}:\n" + "".join(f"  {f}: {yaml.safe_dump(v, default_flow_style=True, width=999).removesuffix('...\n').strip()}\n"
                   for f, v in sites[k].items() if (f, v) != ("link", sites[k]["url"])) for k in sorted(best)))
    print(f"{len(data)} candidates, {len(sites)} convertible, {len(good)} pass, {len(best)} kept")
